import fs from "node:fs";
const root = process.argv[2];
const regular = `chats-circle users-three star archive gear-six magnifying-glass note-pencil x push-pin speaker-slash at caret-down caret-up caret-right caret-left plus users megaphone
dots-three-vertical dots-three phone video-camera arrow-left sidebar-simple check checks clock warning-circle arrow-bend-up-left arrow-bend-up-right smiley copy pencil-simple trash info
check-circle download-simple play pause microphone file-text map-pin user chart-bar calendar-blank image camera eye prohibit timer link arrow-down arrow-up share-fat sticker gif paperclip
paper-plane-right phone-x phone-incoming bell bell-slash sign-out moon sun palette shield-check lock database keyboard user-circle qr-code device-mobile magnifying-glass-plus magnifying-glass-minus
speaker-high hand-waving globe crown user-plus user-minus link-simple arrow-counter-clockwise heart check-square arrow-square-out warning wifi-slash funnel text-aa envelope-simple tray eraser images
circle-notch number-circle-one file-pdf file-zip file-image file-audio file-video file file-doc file-xls headphones arrow-clockwise sign-in chat-circle-dots lightning monitor list-bullets address-book
circle arrows-out-simple hash chat-circle user-list code text-b text-italic text-strikethrough clock-counter-clockwise door-open shield smiley-sticker export flag thumbs-up arrow-right
phone-slash video-camera-slash broom hard-drives sparkle app-window bell-ringing cursor-click magic-wand rows squares-four`.split(/\s+/).filter(Boolean);
const fill = `chats-circle users-three star archive gear-six push-pin play pause microphone paper-plane-right heart check-circle warning-circle speaker-slash map-pin file-text phone phone-x circle smiley megaphone lock crown caret-down bell-slash timer eye image user users sticker lightning`.split(/\s+/).filter(Boolean);
const inner = (file) => {
  if (!fs.existsSync(file)) return null;
  const svg = fs.readFileSync(file, "utf8");
  return svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
};
const out = {};
const missing = [];
for (const n of [...new Set(regular)]) {
  const v = inner(`${root}/regular/${n}.svg`);
  if (v) out[n] = v; else missing.push(n);
}
for (const n of [...new Set(fill)]) {
  const v = inner(`${root}/fill/${n}-fill.svg`);
  if (v) out[`${n}-fill`] = v; else missing.push(n + "-fill");
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(process.argv[3], `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT). Do not edit by hand.\n\nexport const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`);
console.log("icons:", Object.keys(out).length, "missing:", missing.join(", ") || "none");
